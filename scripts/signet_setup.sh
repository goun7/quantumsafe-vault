#!/usr/bin/env bash
# Signet environment bootstrap (Phase 1 milestone): a real-network rehearsal
# of the full vault lifecycle WITHOUT mainnet value at risk.
#
# Usage:
#   scripts/signet_setup.sh bootstrap [datadir]   # node + wallet + first coins
#   scripts/signet_setup.sh status    [datadir]   # chain tip, wallet, vault address
#   scripts/signet_setup.sh vault-fund [sats]     # fund the demo vault address
#   scripts/signet_setup.sh lifecycle             # psbt-live signet round trip
#
# Requirements: bitcoind v26+ on PATH, the repo built (cargo build -p qsv-cli),
# a signet faucet source for coins (the global signet faucet or a friendly miner).
#
# SAFETY: signet coins have NO monetary value; every command here is
# deliberately read-only or signet-scoped. Nothing in this script ever
# touches mainnet (network is pinned to --signet in every RPC/CLI call).
set -euo pipefail
cd "$(dirname "$0")/.."

CMD="${1:-}"
# $2 means the funding AMOUNT for vault-fund but the datadir otherwise —
# resolve it per-command so `vault-fund 20000` can't poison the datadir.
if [ "$CMD" = "vault-fund" ]; then
    DATADIR="${3:-$HOME/.signet-qsv}"
else
    DATADIR="${2:-$HOME/.signet-qsv}"
fi
NET="signet"
CLI="cargo run -q -p qsv-cli --"

die() { echo "error: $*" >&2; exit 1; }

rpc() {
    # Read-only JSON-RPC via the cookie file (no wallet auth for chain calls;
    # wallet calls run through bitcoin-cli scoped to the signet datadir).
    bitcoin-cli -datadir="$DATADIR" -signet "$@"
}

wallet_rpc() {
    bitcoin-cli -datadir="$DATADIR" -signet -rpcwallet=qsv "$@"
}

bootstrap() {
    command -v bitcoind >/dev/null || die "bitcoind not on PATH"
    command -v bitcoin-cli >/dev/null || die "bitcoin-cli not on PATH"

    mkdir -p "$DATADIR"
    if [ ! -f "$DATADIR/signet/.cookie" ] && [ ! -f "$DATADIR/.cookie" ]; then
        cat > "$DATADIR/bitcoin.conf" <<EOF
# QuantumSafe-Vault signet node (generated by scripts/signet_setup.sh)
signet=1
server=1
txindex=0
daemon=1
# Read-only posture for the watchtower/psbt-live scans (cookie auth):
fallback_fee=0.0002
EOF
        echo "── starting bitcoind (signet) with datadir $DATADIR"
        bitcoind -datadir="$DATADIR"
        sleep 3
    fi
    rpc getblockchaininfo >/dev/null || die "node did not come up (check $DATADIR)"

    echo "── creating the qsv wallet (signet coins only)"
    bitcoin-cli -datadir="$DATADIR" -signet createwallet qsv 2>/dev/null \
        || echo "   (wallet qsv already exists)"

    local addr
    addr=$(wallet_rpc getnewaddress "" bech32)
    echo
    echo "═══ SIGNET BOOTSTRAP DONE ═══"
    echo "  node:      $DATADIR (signet, daemon)"
    echo "  tip:       $(rpc getblockcount)"
    echo "  faucet:    send signet tBTC to this address and mine/wait for 1 conf:"
    echo "             $addr"
    echo "  next:      scripts/signet_setup.sh status   → verify ≥1 signet coin"
    echo "             scripts/signet_setup.sh vault-fund 20000 → fund the demo vault"
    echo "             scripts/signet_setup.sh lifecycle       → real-network round trip"
}

status() {
    rpc getblockchaininfo >/dev/null || die "node not running at $DATADIR"
    echo "═══ SIGNET STATUS ═══"
    echo "  chain:      $(rpc getblockchaininfo | grep -o '"chain": "[^"]*"')"
    echo "  tip:        $(rpc getblockcount)"
    echo "  best hash:  $(rpc getbestblockhash)"
    local bal
    bal=$(wallet_rpc getbalance 2>/dev/null || echo "wallet missing")
    echo "  wallet qsv: $bal signet BTC"
    echo "  vault addr (demo provisioning):"
    $CLI vault-setup --network signet | grep "Address (signet)" || true
}

vault_fund() {
    # $1 is the subcommand in this dispatch; the amount lives in $2.
    local sats="${2:-20000}"
    local amount
    amount=$(awk "BEGIN{printf \"%.8f\", $sats/100000000}")
    local vault_addr
    vault_addr=$($CLI vault-setup --network signet | grep "Address (signet)" \
        | sed 's/.*: //')
    [ -n "$vault_addr" ] || die "cannot derive the vault address"
    echo "── funding the demo vault: $sats sats → $vault_addr"
    # Explicit fee rate: signet has no fee estimate and bitcoin.conf's
    # fallback_fee (20 sat/vB) would dwarf a faucet-funded budget. 1 sat/vB
    # is the node's min relay rate — safe until the first rejected send.
    wallet_rpc -named sendtoaddress address="$vault_addr" amount="$amount" \
        fee_rate="${FEE_RATE:-1}" >/dev/null
    # 1 confirmation so scantxoutset sees the coin.
    wallet_rpc -generate 1 >/dev/null 2>&1 || true
    echo "   sent. signet blocks are ~10 min — wait for 1 conf, then:"
    echo "   $CLI psbt-live --datadir $DATADIR --network signet --rpc-port 38332"
    echo "   (psbt-live uses scantxoutset: no wallet ownership of the vault needed)"
}

lifecycle() {
    echo "── REAL-NETWORK ROUND TRIP (signet): psbt-live end-to-end"
    echo "   build-only pass first (coordinator/device split discipline):"
    # FEE_SAT passthrough: after a heartbeat rotation the coin may be
    # SMALLER than the default 1500 fee (fail-closed "fee exceeds the
    # aggregate input value") — the lap then continues with FEE_SAT=800.
    $CLI psbt-live --datadir "$DATADIR" --network signet \
        $( [ -f "$DATADIR/signet/.cookie" ] && echo "--rpc-port 38332" ) \
        --fee-sat "${FEE_SAT:-1500}" \
        --build-only --dir signet-artifacts
    echo
    echo "   full pass (both devices sign, finalize, broadcast → signet mempool):"
    $CLI psbt-live --datadir "$DATADIR" --network signet \
        $( [ -f "$DATADIR/signet/.cookie" ] && echo "--rpc-port 38332" ) \
        --fee-sat "${FEE_SAT:-1500}" \
        --dir signet-artifacts
    echo
    echo "═══ signet lifecycle COMPLETE — the mempool accepted the vault spend ═══"
}

case "$CMD" in
    bootstrap) bootstrap ;;
    status)    status ;;
    vault-fund) vault_fund "$@" ;;
    lifecycle) lifecycle ;;
    *) echo "usage: $0 {bootstrap|status|vault-fund [sats]|lifecycle} [datadir]" >&2; exit 2 ;;
esac
